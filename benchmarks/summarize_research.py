"""Render the checked-in research reports without choosing dispatch profiles."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = {
    "Hybrid forward": "results-hybrid-forward.json",
    "Hybrid forward + backward": "results-hybrid-backward.json",
    "Log tails forward": "results-log-tails-forward.json",
    "Log tails forward + backward": "results-log-tails-backward.json",
}


def table(headers, rows):
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
        *["| " + " | ".join(map(str, row)) + " |" for row in rows],
        "",
    ]


def valid(records):
    return [r for r in records if r["status"] == "ok" and r["accuracy_passed"]]


def same_workload(a, b):
    return all(a[key] == b[key] for key in ["device", "dtype", "n", "batch_size"])


def main():
    reports = {
        name: json.loads((ROOT / "benchmarks" / filename).read_text())
        for name, filename in REPORTS.items()
    }
    lines = [
        "# Log tails, ShiftConvolve, and hybrid convolution experiments",
        "",
        "Generated by `python -m benchmarks.summarize_research` from the raw reports.",
        "All timings are workload-specific. DP remains the default; these experiments",
        "do not add hybrid auto-dispatch profiles.",
        "",
        "## Run coverage",
        "",
    ]
    rows = []
    failures = []
    for name, report in reports.items():
        records = report["records"]
        ok = valid(records)
        skipped = [r for r in records if r["status"] == "skipped"]
        bad = [
            r
            for r in records
            if r["status"] == "error"
            or (r["status"] == "ok" and not r["accuracy_passed"])
        ]
        failures.extend(bad)
        rows.append([name, len(ok), len(skipped), len(bad)])
    lines += table(["Experiment", "Passed", "Skipped", "Failed"], rows)
    runtimes = {
        json.dumps(r["runtime"], sort_keys=True)
        for report in reports.values()
        for r in valid(report["records"])
    }
    for runtime in sorted(runtimes):
        r = json.loads(runtime)
        lines.append(
            f"- {r['device']}: {r['hardware']}; PyTorch {r['torch']}; CUDA {r['cuda']}; threads={r['threads']}; {r['platform']}."
        )
    lines += [
        "",
        "Each case has a subprocess deadline and a tensor-workspace budget. Skips",
        "and their reasons remain in the raw JSON. CPU peak memory is process RSS",
        "including runtime/oracle/caches; CUDA memory is incremental peak allocated",
        "tensor memory. These measurements are not interchangeable.",
        "",
        "## Hybrid DP–FFT",
        "",
        "All five requested block sizes (8, 16, 32, 64, 128) are measured. Blocks",
        "larger than n reduce to n and therefore duplicate an effective configuration.",
        "The following are illustrative float64, B=16 inference medians; 'best' means",
        "the lowest recorded median, not a universal or statistically proven optimum.",
        "",
    ]
    forward = valid(reports["Hybrid forward"]["records"])
    rows = []
    chosen = []
    for tree in forward:
        if (
            tree["method"] != "fft_tree"
            or tree["dtype"] != "float64"
            or tree["batch_size"] != 16
            or tree["n"] == 32
        ):
            continue
        candidates = [
            r for r in forward if r["method"] == "fft_hybrid" and same_workload(r, tree)
        ]
        if not candidates:
            continue
        best = min(candidates, key=lambda r: r["median_seconds"])
        chosen.append(best)
        noisy = any(r["iqr_seconds"] > 0.2 * r["median_seconds"] for r in [tree, best])
        rows.append(
            [
                tree["device"],
                tree["n"],
                f"{tree['median_seconds'] * 1e3:.3f}",
                best["block_size"],
                f"{best['median_seconds'] * 1e3:.3f}",
                f"{tree['median_seconds'] / best['median_seconds']:.2f}x",
                "high IQR" if noisy else "within IQR gate",
            ]
        )
    lines += table(
        [
            "Device",
            "n",
            "Tree ms",
            "Best block",
            "Hybrid ms",
            "Tree/hybrid",
            "Timing noise",
        ],
        rows,
    )
    for tree in forward:
        if (
            tree["method"] != "fft_tree"
            or tree["dtype"] != "float64"
            or tree["batch_size"] != 16
            or tree["n"] != 2048
        ):
            continue
        by_block = {
            r["block_size"]: r
            for r in forward
            if r["method"] == "fft_hybrid" and same_workload(r, tree)
        }
        if 32 in by_block and 128 in by_block:
            lines.append(
                f"- {tree['device']}, B=16, n=2048: default block 32 took {by_block[32]['median_seconds'] * 1e3:.3f} ms; "
                f"block 128 took {by_block[128]['median_seconds'] * 1e3:.3f} ms, versus {tree['median_seconds'] * 1e3:.3f} ms for the plain FFT tree."
            )
    lines.append("")
    hybrids = [r for r in forward if r["method"] == "fft_hybrid"]
    for dtype in ["float32", "float64"]:
        subset = [r for r in hybrids if r["dtype"] == dtype]
        if subset:
            lines.append(
                f"- {dtype}: maximum hybrid absolute PMF error across five regimes = {max(r['max_abs_error'] for r in subset):.3g}."
            )
    lines += [
        "",
        "For training, the table below includes the forward pass and gradient computation.",
        "The workload is CUDA, float64, B=16, n=512; the hybrid row uses that",
        "workload's fastest measured training block, which can differ from inference.",
        "",
    ]
    training = [
        r
        for r in valid(reports["Hybrid forward + backward"]["records"])
        if r["device"] == "cuda"
        and r["dtype"] == "float64"
        and r["batch_size"] == 16
        and r["n"] == 512
    ]
    rows = []
    for method in ["dp", "fft_tree", "fft_hybrid"]:
        candidates = [r for r in training if r["method"] == method]
        if not candidates:
            continue
        row = min(candidates, key=lambda r: r["median_seconds"])
        rows.append(
            [
                method
                + (f" (block {row['block_size']})" if method == "fft_hybrid" else ""),
                f"{row['median_seconds'] * 1e3:.3f}",
                f"{row['peak_bytes'] / 1024**2:.3f}",
                f"{row['max_abs_gradient_error']:.3g}",
            ]
        )
    lines += table(
        [
            "Method",
            "Forward + backward ms",
            "CUDA peak tensor MiB",
            "Gradient error vs DP",
        ],
        rows,
    )
    lines += [
        "## Log tails and shifted FFT",
        "",
        "The oracle evaluates binomial sums and their derivatives at 100 decimal digits",
        "using the exact supplied floating-point probability. Errors below use logs,",
        "so an underflowed ordinary probability is never the reference. Relative",
        "probability errors are computed as abs(expm1(log_result-log_reference)).",
        "",
    ]
    logs = valid(reports["Log tails forward"]["records"])
    rows = []
    for dtype in ["float32", "float64"]:
        for method in ["dp", "shift_fft"]:
            subset = [r for r in logs if r["dtype"] == dtype and r["method"] == method]
            if subset:
                rows.append(
                    [
                        dtype,
                        method,
                        f"{max(r['max_log_error'] for r in subset):.3g}",
                        f"{max(r['max_relative_probability_error'] for r in subset):.3g}",
                        sum(r["ordinary_underflow"] for r in subset),
                    ]
                )
    lines += table(
        [
            "Output dtype",
            "Method",
            "Max log error",
            "Max relative probability error",
            "Underflow cases recovered",
        ],
        rows,
    )
    lines += [
        "Float32 outputs quantize large logarithms even though both implementations",
        "compute internally in float64. The reported error includes that quantization.",
        "",
        "Illustrative inference and training timings: float64, B=16, n=2048, fair",
        "coins, P(X>2045). The true log probability is finite while ordinary float64",
        "probability arithmetic underflows.",
        "",
    ]
    rows = []
    for phase in ["Log tails forward", "Log tails forward + backward"]:
        for r in valid(reports[phase]["records"]):
            if (
                r["dtype"] == "float64"
                and r["batch_size"] == 16
                and r["n"] == 2048
                and r["regime"] == "fair_upper"
            ):
                rows.append(
                    [
                        phase,
                        r["device"],
                        r["method"],
                        f"{r['median_seconds'] * 1e3:.3f}",
                        r["measurements"],
                        f"{r['peak_bytes'] / 1024**2:.3f}",
                        r["peak_kind"],
                    ]
                )
    lines += table(
        [
            "Phase",
            "Device",
            "Method",
            "ms",
            "Timing samples",
            "Peak MiB",
            "Memory metric",
        ],
        rows,
    )
    lines += [
        "Shifted FFT accelerates only its forward algorithm. Its first-order backward",
        "uses nonnegative leave-one-out densities from prefix/suffix log DP. Training",
        "retains DP complexity; it is not an FFT-complexity backward.",
        "Long cases can have few timing samples within the bounded measurement window;",
        "the raw reports include sample counts and IQR rather than implying universal gains.",
        "For these fixed-width tails, truncated log DP is O(n), whereas shifted FFT",
        "is O(n log² n). Any observed inference gain reflects tensor parallelism and",
        "reduced Python-loop overhead, not a better asymptotic bound than truncated DP.",
        "",
        "## Reproduction and limits",
        "",
        "See [benchmark commands](../benchmarks/README.md) and",
        "[numerical contracts](numerics.md). Tests also compare heterogeneous distributions",
        "with a 400-digit independent recurrence, including deterministic boundaries,",
        "near-one logs, extreme tails, and gradients. The timed log-tail cases use",
        "homogeneous binomial instances so large-input reference calculations remain bounded.",
        "The methods do not establish arbitrary-precision output guarantees; FFTs still",
        "have roundoff, and log outputs/gradients still have floating-point limits.",
        "",
    ]
    destination = ROOT / "docs/research-results.md"
    destination.write_text("\n".join(lines))
    print(destination)
    if failures:
        raise SystemExit(
            f"{len(failures)} experiment cases failed; inspect raw reports"
        )


if __name__ == "__main__":
    main()
